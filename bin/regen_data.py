"""Regenerate src/logicxkit/data/logic and data/donors from the public golden corpus (`tests/corpus/`).

    bin/run python bin/regen_data.py

Every template is a record Logic wrote in a public save of a blank project, so the package
ships Logic's own bytes and nothing vendor-authored.
"""
from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))
import _goldens  # noqa: E402
from logicxkit.logic.services.binding import channels  # noqa: E402
from logicxkit.logic.services.channel_alloc import mixer_record  # noqa: E402
from logicxkit.logic.services.environment import ENV_TAG, object_id_of  # noqa: E402
from logicxkit.logic.services.groups import (  # noqa: E402
    EVENT,
    EVENT_FADER_AT,
    EVENT_OBJECT_AT,
    EVENT_VALUE_AT,
    EVENT_VALUE_HI_AT,
    EVENT_VALUE_LO_AT,
    FADER_IDS,
    TAIL,
    read_groups,
)
from logicxkit.logic.services.insert import HEADER, project_records  # noqa: E402
from logicxkit.logic.services.recbuild import slot_of  # noqa: E402
from logicxkit.logic.services.recdiff import load_project_data  # noqa: E402
from logicxkit.logic.services.sends import is_send  # noqa: E402
from logicxkit.logic.services.stacks import read_stacks  # noqa: E402
from logicxkit.logic.services.tracklist import arrange_run, flat_run, row_object  # noqa: E402

TEXT_HEAD = 98                      # a qSxT's fixed head; the section name follows
SLOT_KEYS = range(2, 20)            # a channel's plug-in and property records

OUT = ROOT / "src" / "logicxkit" / "data"
SOURCE = ("Logic Pro 12.3.1 on a blank project: {what} (public corpus {a} -> {b}; "
          "regenerated by bin/regen_data.py)")


def _load(key: str) -> bytes:
    p = _goldens.path(key)
    if p is None:
        raise SystemExit(f"golden {key!r} is not under tests/corpus — the checkout is incomplete")
    return load_project_data(p)


def _new(pair: tuple[str, str]) -> list:
    """Records of the second save whose (tag, payload) the first lacks."""
    a, b = (project_records(_load(k)) for k in pair)
    seen = {(r.tag, r.raw[HEADER:]) for r in a}
    return [r for r in b if (r.tag, r.raw[HEADER:]) not in seen]


def _split(raw: bytes) -> dict:
    return {"header": raw[:HEADER].hex(), "payload": raw[HEADER:].hex()}


def _source(pair: tuple[str, str], what: str) -> str:
    return SOURCE.format(what=what, a=pair[0], b=pair[1])


def channel(pair: tuple[str, str], label: str) -> dict:
    """The mixer record of the strip labelled ``label`` in the second save."""
    data = _load(pair[1])
    owner = next((o for o, c in channels(data).items() if c.label == label), None)
    if owner is None:
        raise SystemExit(f"{pair[1]}: no strip labelled {label!r}")
    return {"source": _source(pair, f"the {label} strip"), **_split(mixer_record(project_records(data), owner))}


def send(pair: tuple[str, str]) -> dict:
    """The one send the second save added."""
    added = [r for r in _new(pair) if is_send(r)]
    if len(added) != 1:
        raise SystemExit(f"{pair}: {len(added)} new send record(s), wanted one")
    return {"source": _source(pair, "the send the second save added"), **_split(added[0].raw)}


def _bare_event(event: bytes, fader: str) -> str:
    e = bytearray(event)
    struct.pack_into("<I", e, EVENT_OBJECT_AT, 0)
    struct.pack_into("<I", e, EVENT_FADER_AT, FADER_IDS[fader])
    struct.pack_into("<I", e, EVENT_VALUE_AT, 0)
    struct.pack_into("<H", e, EVENT_VALUE_HI_AT, 0)
    struct.pack_into("<H", e, EVENT_VALUE_LO_AT, 0)
    return bytes(e).hex()


def group(pair: tuple[str, str], name: str) -> dict:
    """The group triple named ``name``: the `qeSM`, its `karT` marker and its `qSvE` events."""
    records = project_records(_load(pair[1]))
    g = next((g for g in read_groups(_load(pair[1])) if g.name == name), None)
    if g is None:
        raise SystemExit(f"{pair[1]}: no group named {name!r}")
    qesm, marker, qsve = (records[g.start + k].raw for k in range(3))
    events = qsve[HEADER:-TAIL]
    if not events or len(events) % EVENT:
        raise SystemExit(f"{pair[1]}: group {name!r} has no member events to pattern on")
    return {"source": _source(pair, f"the group {name!r}"),
            "qesm_header": qesm[:HEADER].hex(), "qesm_payload": qesm[HEADER:].hex(),
            "marker_header": marker[:HEADER].hex(), "qsve_header": qsve[:HEADER].hex(),
            "qsve_tail": qsve[-TAIL:].hex(),
            "member_events": {f: _bare_event(events[:EVENT], f) for f in FADER_IDS},
            "notes": "member_events: one event per linked fader, from the group's first event "
                     "with the object id (+4), fader id (+12) and value (+8, +20, +30) reset; "
                     "the writer stamps all three"}


def stack_folder(pair: tuple[str, str], name: str) -> dict:
    """The folder stack ``name``: its Sub strip, header object, arrange row and flat row."""
    data = _load(pair[1])
    records = project_records(data)
    stack = next((s for s in read_stacks(data, None) if s.name == name), None)
    if stack is None:
        raise SystemExit(f"{pair[1]}: no stack named {name!r}")
    obj = next(r.raw for r in records if r.tag == ENV_TAG and object_id_of(r) == stack.object_id)
    run = arrange_run(records)
    row = next(records[i].raw for i in run if row_object(records[i].raw) == stack.object_id)
    flat = next(records[i].raw for i in flat_run(records, run)
                if row_object(records[i].raw) == stack.object_id)
    roles = {"strip": mixer_record(records, stack.owner), "object": obj, "row": row, "flat_row": flat}
    return {"source": _source(pair, f"the folder stack {name!r} Logic created over three tracks"),
            "records": {role: _split(raw) for role, raw in roles.items()}}


def inst_track(pair: tuple[str, str], label: str) -> dict:
    """The instrument slot and property records Logic gave the strip labelled ``label``."""
    data = _load(pair[1])
    owner = next((o for o, c in channels(data).items() if c.label == label), None)
    if owner is None:
        raise SystemExit(f"{pair[1]}: no strip labelled {label!r}")
    recs = [r for r in project_records(data) if r.tag == b"UCuA" and r.owner == owner and r.key in SLOT_KEYS]
    return {"_": _source(pair, f"the {label} strip's slot records; owner re-stamped on use"),
            "records": {str(r.key): r.raw.hex() for r in sorted(recs, key=lambda r: r.key)}}


def section_text(pair: tuple[str, str], name: str) -> dict:
    """The name record of the section called ``name``, less the name itself."""
    text = name.encode("ascii") + b"\0"
    text += b"\0" * (len(text) % 2)
    hit = next((r for r in _new(pair) if r.tag == b"qSxT" and r.raw[HEADER + TEXT_HEAD:] == text), None)
    if hit is None:
        raise SystemExit(f"{pair}: no new section text record named {name!r}")
    return {"source": _source(pair, f"the section {name!r}'s name record"),
            "header": hit.raw[:HEADER].hex(), "head": hit.raw[HEADER:HEADER + TEXT_HEAD].hex()}


def arrangement_track(pair: tuple[str, str]) -> dict:
    """Everything Logic added for the arrangement track and its first section: the section
    and track sequence triples with the `snrT` after the last `tSxT`, the `OgnS` before the
    first `rpyH`, the last `MneG` and the empty text record."""
    records = project_records(_load(pair[1]))
    anchor = max(i for i, r in enumerate(records) if r.tag == b"tSxT")
    run = records[anchor + 1:anchor + 8]
    if [r.tag for r in run] != [b"qeSM", b"karT", b"qSvE"] * 2 + [b"snrT"]:
        raise SystemExit(f"{pair[1]}: no two sequence triples and snrT after the last tSxT")
    first_rpyh = next(i for i, r in enumerate(records) if r.tag == b"rpyH")
    ogns = max(i for i, r in enumerate(records[:first_rpyh]) if r.tag == b"OgnS")
    mneg = max(i for i, r in enumerate(records) if r.tag == b"MneG")
    empty = next(r for r in records if r.tag == b"qSxT" and slot_of(r.raw) == 0 and r.raw[HEADER + TEXT_HEAD:] == b"\0")
    roles = dict(zip(("section_qesm", "section_marker", "section_qsve", "track_qesm", "track_marker",
                      "track_qsve", "snrt"), (r.raw for r in run)))
    roles |= {"ogns": records[ogns].raw, "mneg": records[mneg].raw, "text_empty": empty.raw}
    return {"source": _source(pair, "the arrangement track shown and its first section added"),
            "records": {role: _split(raw) for role, raw in roles.items()}}


def midi_region(pair: tuple[str, str], track_label: str) -> dict:
    """The region Logic made on the strip labelled ``track_label``: its sequence triple and the
    song container's 80-byte entry for it."""
    from logicxkit.logic.services.regions import ENTRY, placements, song_container
    from logicxkit.logic.services.sequence import sequences, triple_by_slot
    data = _load(pair[1])
    records = project_records(data)
    run = arrange_run(records)
    song = song_container(records, run)
    payload = records[song.end].raw[HEADER:]
    labels = {}
    from logicxkit.logic.services.stacks import read_tracks
    names = {r["object_id"]: r["name"] for r in read_tracks(data, None)}
    entries = [(off, oid) for off, oid, _row in placements(records) if names.get(oid) == track_label]
    if len(entries) != 1:
        raise SystemExit(f"{pair[1]}: {len(entries)} region(s) on {track_label!r}, wanted one")
    off, _oid = entries[0]
    entry = payload[off:off + ENTRY]
    slot = struct.unpack_from("<I", entry, 32)[0]
    t = triple_by_slot(sequences(records), slot)
    roles = {"qesm": records[t.start].raw, "marker": records[t.start + 1].raw, "qsve": records[t.end].raw, "entry": entry}
    return {"source": _source(pair, f"the empty MIDI region on {track_label!r} (Pencil tool click)"),
            "records": {role: _split(raw) if role != "entry" else {"payload": raw.hex()} for role, raw in roles.items()}}

def audio_region(pair: tuple[str, str]) -> dict:
    """The audio file record, region record and song-container entry Logic added for one
    imported WAV."""
    from logicxkit.logic.services.regions import ENTRY, TAIL, song_container
    new = _new(pair)
    lfua = [r for r in new if r.tag == b"lFuA"]
    grua = [r for r in new if r.tag == b"gRuA"]
    if len(lfua) != 1 or len(grua) != 1:
        raise SystemExit(f"{pair}: {len(lfua)} file and {len(grua)} region record(s), wanted one each")
    records = project_records(_load(pair[1]))
    song = song_container(records, arrange_run(records))
    payload = records[song.end].raw[HEADER:]
    entries = [payload[i:i + ENTRY] for i in range(0, len(payload) - TAIL, ENTRY)]
    audio = [e for e in entries if struct.unpack_from("<H", e, 0)[0] == 0x24]
    if len(audio) != 1:
        raise SystemExit(f"{pair[1]}: {len(audio)} audio entries, wanted one")
    return {"source": _source(pair, "one WAV imported with File > Import > Audio File"),
            "records": {"lfua": _split(lfua[0].raw), "grua": _split(grua[0].raw), "entry": {"payload": audio[0].hex()}}}

